function traceGlyph(ctx,g,x,top,scale){
  for(const path of g.paths){
    let cur=[0,0];
    for(const cmd of path){
      const t=cmd[0];
      if(t==='M'){cur=[cmd[1],cmd[2]];ctx.moveTo(x+cur[0]*scale,top+cur[1]*scale)}
      else if(t==='L'){cur=[cmd[1],cmd[2]];ctx.lineTo(x+cur[0]*scale,top+cur[1]*scale)}
      else if(t==='Q'){cur=[cmd[3],cmd[4]];ctx.quadraticCurveTo(x+cmd[1]*scale,top+cmd[2]*scale,x+cmd[3]*scale,top+cmd[4]*scale)}
      else if(t==='C'){cur=[cmd[5],cmd[6]];ctx.bezierCurveTo(x+cmd[1]*scale,top+cmd[2]*scale,x+cmd[3]*scale,top+cmd[4]*scale,x+cmd[5]*scale,top+cmd[6]*scale)}
      else if(t==='A'){
        const sp=arcPoint(cmd[1],cmd[2],cmd[3],cmd[4],cmd[5]);
        if(Math.hypot(cur[0]-sp[0],cur[1]-sp[1])>.001)ctx.lineTo(x+sp[0]*scale,top+sp[1]*scale);
        ctx.ellipse(x+cmd[1]*scale,top+cmd[2]*scale,cmd[3]*scale,cmd[4]*scale,0,cmd[5],cmd[6],cmd[7]);
        cur=arcPoint(cmd[1],cmd[2],cmd[3],cmd[4],cmd[6]);
      }
    }
  }
}
function draw(ctx,text,x,y,size,opts={}){
  const role=normaliseRole(opts.role||'auto');
  const norm=normalizeText(text),scale=size,glyphs=glyphsForRole(size,role);
  const tracking=resolveTracking(opts.tracking,glyphs);
  const width=metrics(norm,tracking,glyphs).width*size;
  const align=opts.align||ctx.textAlign||'left';
  const baseline=opts.baseline||ctx.textBaseline||'alphabetic';
  let startX=x;
  if(align==='center')startX-=width/2;
  else if(align==='right'||align==='end')startX-=width;
  let top=y-size;
  if(baseline==='top'||baseline==='hanging')top=y;
  else if(baseline==='middle')top=y-size*.5;
  else if(baseline==='bottom'||baseline==='ideographic')top=y-size;
  const square=squareStrokeFor(glyphs);
  ctx.save();ctx.beginPath();ctx.lineWidth=1;ctx.lineCap=square?'square':'round';ctx.lineJoin=square?'miter':'round';ctx.strokeStyle=opts.color||ctx.strokeStyle;
  let cursor=startX;
  for(let i=0;i<norm.length;i++){
    const g=lookup(norm[i],glyphs);traceGlyph(ctx,g,cursor,top,scale);cursor+=(g.w+trackingAfter(norm,i,tracking,glyphs))*scale;
  }
  ctx.stroke();ctx.restore();return width;
}
